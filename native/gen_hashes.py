#!/usr/bin/env python3
"""Generate native/sec_hashes.h: the sealed SHA-256 over the APK's
classes*.dex entries (name order) + resources.arsc — the exact bytes
Guard.apkCodeHash() hashes on device — XOR-obfuscated with the same key
as omnisec.c. With no APK argument, writes an all-zero (unsealed) header.
"""
import hashlib
import sys
import zipfile

KEY = [0x3C, 0x5A, 0x71, 0x26]


def apk_code_hash(path):
    md = hashlib.sha256()
    with zipfile.ZipFile(path) as z:
        names = sorted(n for n in z.namelist()
                       if __import__("re").fullmatch(r"classes\d*\.dex", n))
        if not names:
            raise SystemExit("no dex entries in " + path)
        for n in names:
            md.update(z.read(n))
        md.update(z.read("resources.arsc"))
    return md.hexdigest()


def main():
    if len(sys.argv) > 1:
        hexhash = apk_code_hash(sys.argv[1])
    else:
        hexhash = "0" * 64
    raw = hexhash.encode()
    enc = [b ^ KEY[i % 4] for i, b in enumerate(raw)]
    body = ", ".join("0x%02x" % b for b in enc)
    out = ("/* generated by gen_hashes.py — do not edit by hand */\n"
           "static const unsigned char DEX_EXPECTED[] = { %s };\n" % body)
    with open("native/sec_hashes.h", "w") as f:
        f.write(out)
    print("sealed dex+arsc sha256:", hexhash)


if __name__ == "__main__":
    main()
